package com.eiga.model;
public class CheckIn {
    private String checkInId, bookingId, userId, theatreId, showId, checkedInAt, staffId, source, status;
    public String getCheckInId() { return checkInId; } public void setCheckInId(String checkInId) { this.checkInId = checkInId; }
    public String getBookingId() { return bookingId; } public void setBookingId(String bookingId) { this.bookingId = bookingId; }
    public String getUserId() { return userId; } public void setUserId(String userId) { this.userId = userId; }
    public String getTheatreId() { return theatreId; } public void setTheatreId(String theatreId) { this.theatreId = theatreId; }
    public String getShowId() { return showId; } public void setShowId(String showId) { this.showId = showId; }
    public String getCheckedInAt() { return checkedInAt; } public void setCheckedInAt(String checkedInAt) { this.checkedInAt = checkedInAt; }
    public String getStaffId() { return staffId; } public void setStaffId(String staffId) { this.staffId = staffId; }
    public String getSource() { return source; } public void setSource(String source) { this.source = source; }
    public String getStatus() { return status; } public void setStatus(String status) { this.status = status; }
}
